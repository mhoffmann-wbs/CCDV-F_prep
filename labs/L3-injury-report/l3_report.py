"""L3 offline helpers: the week 4 injury report (data and PDF), the extraction schema,
content blocks for each way of sending a document, and scoring against the truth.

Nothing here calls the API. The PDF is written by a tiny, dependency-free writer, so
`injury-report-week4.pdf` can be regenerated byte for byte (test_l3_report.py checks it).
"""

from __future__ import annotations

import base64
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, Field

LAB_DIR = Path(__file__).resolve().parent
