Practice = Literal["DNP", "Limited", "Full"]
GameStatus = Literal["Out", "Doubtful", "Questionable", "No status"]


# --------------------------------------------------------------------------- #
# The extraction schema. Field descriptions steer the model; list lengths are
# checked in code because structured outputs don't support minItems/maxItems.
# --------------------------------------------------------------------------- #


class InjuryEntry(BaseModel):
    team: str = Field(description='Team abbreviation exactly as printed, e.g. "POR".')
    player: str = Field(description="Player's full name exactly as printed.")
    position: str = Field(description='Position abbreviation, e.g. "WR".')
    injury: str = Field(description='The injury as printed, e.g. "Hamstring". Use "Not injury related" for rest days.')
    practice: list[Practice] = Field(description="Practice participation for Wednesday, Thursday and Friday, in that order.")
    game_status: GameStatus = Field(description='Game status as printed; "No status" when the column is blank.')


class InjuryReport(BaseModel):
    week: int = Field(description="The week number in the report title.")
    entries: list[InjuryEntry] = Field(description="Every player row in the report, in printed order.")


