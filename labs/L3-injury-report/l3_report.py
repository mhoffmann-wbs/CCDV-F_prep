# --------------------------------------------------------------------------- #
# A minimal PDF writer: text, lines, Helvetica, one game per page.
# --------------------------------------------------------------------------- #

COLUMNS = [("Player", 50), ("Pos", 200), ("Injury", 240), ("Wed", 360), ("Thu", 410), ("Fri", 460), ("Game status", 505)]


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _text(x: float, y: float, size: int, text: str, bold: bool = False) -> str:
    return f"BT /{'F2' if bold else 'F1'} {size} Tf {x} {y} Td ({_escape(text)}) Tj ET"


def _line(x1: float, y1: float, x2: float, y2: float) -> str:
    return f"0.5 w {x1} {y1} m {x2} {y2} l S"


def _page_ops(away: str, home: str, page: int, pages: int) -> str:
    ops = [
        _text(50, 790, 16, f"Official Injury Report - Week {WEEK}", bold=True),
        _text(50, 770, 11, f"{TEAMS[away]} ({away}) at {TEAMS[home]} ({home})"),
        _text(50, 755, 9, "Practice: DNP = did not participate, Limited = limited participation, Full = full participation."),
        _text(50, 743, 9, "Game status: Out, Doubtful or Questionable. A blank status means the player is expected to play."),
    ]
    y = 710
    for team in (away, home):
        ops.append(_text(50, y, 12, f"{TEAMS[team]} ({team})", bold=True))
        y -= 18
        ops.extend(_text(x, y, 9, label, bold=True) for label, x in COLUMNS)
        ops.append(_line(50, y - 4, 570, y - 4))
        y -= 18
        for e in (e for e in TRUTH.entries if e.team == team):
            status = "" if e.game_status == "No status" else e.game_status
            cells = [e.player, e.position, e.injury, *e.practice, status]
            ops.extend(_text(x, y, 10, cell) for (_, x), cell in zip(COLUMNS, cells))
            y -= 16
        y -= 20
    ops.append(_text(50, 60, 8, f"Fictional league. Issued Friday of week {WEEK}. Page {page} of {pages}."))
    return "\n".join(ops)


def build_pdf() -> bytes:
    """A two-page PDF, deterministic (no dates or ids), readable by any PDF viewer."""
    pages = [_page_ops(away, home, i + 1, len(GAMES)) for i, (away, home) in enumerate(GAMES)]
    n = len(pages)
    page_ids = [5 + 2 * i for i in range(n)]
    objects = {
        1: "<< /Type /Catalog /Pages 2 0 R >>",
        2: f"<< /Type /Pages /Kids [{' '.join(f'{p} 0 R' for p in page_ids)}] /Count {n} >>",
        3: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        4: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    }
    for i, ops in enumerate(pages):
        page_id, content_id = page_ids[i], page_ids[i] + 1
        objects[page_id] = (
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] "
            f"/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {content_id} 0 R >>"
        )
        stream = ops.encode("latin-1")
        objects[content_id] = f"<< /Length {len(stream)} >>\nstream\n{ops}\nendstream"
    info_id = max(objects) + 1
    objects[info_id] = f"<< /Title (Official Injury Report - Week {WEEK}) >>"

    out = bytearray(b"%PDF-1.4\n")
    offsets = {}
    for oid in sorted(objects):
        offsets[oid] = len(out)
        out += f"{oid} 0 obj\n{objects[oid]}\nendobj\n".encode("latin-1")
    xref = len(out)
    out += f"xref\n0 {info_id + 1}\n0000000000 65535 f \n".encode()
    out += "".join(f"{offsets[i]:010d} 00000 n \n" for i in range(1, info_id + 1)).encode()
    out += f"trailer\n<< /Size {info_id + 1} /Root 1 0 R /Info {info_id} 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


# --------------------------------------------------------------------------- #
# Content blocks: the same document sent three ways.
# --------------------------------------------------------------------------- #


def pdf_base64_block(pdf: bytes, **extra: Any) -> dict[str, Any]:
    """The bytes travel with EVERY request. Fine once; wasteful for repeated questions."""
    data = base64.standard_b64encode(pdf).decode()
    return {"type": "document", "source": {"type": "base64", "media_type": "application/pdf", "data": data}, **extra}


def pdf_file_block(file_id: str, **extra: Any) -> dict[str, Any]:
    """Upload once with the Files API, then reference the id: the request stays small."""
    return {"type": "document", "source": {"type": "file", "file_id": file_id}, **extra}


IMAGE_TYPES = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".gif": "image/gif", ".webp": "image/webp"}


def image_block(path: Path) -> dict[str, Any]:
    media_type = IMAGE_TYPES.get(path.suffix.lower())
    if media_type is None:
        raise ValueError(f"unsupported image type {path.suffix}; use one of {', '.join(IMAGE_TYPES)}")
    data = base64.standard_b64encode(path.read_bytes()).decode()
    return {"type": "image", "source": {"type": "base64", "media_type": media_type, "data": data}}


# --------------------------------------------------------------------------- #
# Scoring: the schema guarantees the shape; only a comparison shows the facts.
# --------------------------------------------------------------------------- #

FIELDS = ("position", "injury", "practice", "game_status")


def _key(e: InjuryEntry) -> tuple[str, str]:
    return e.team.strip().upper(), " ".join(e.player.split()).lower()


def score(report: InjuryReport, truth: InjuryReport = TRUTH) -> dict[str, Any]:
    """Compare an extraction with the truth: missing and extra rows, and field mismatches."""
    want = {_key(e): e for e in truth.entries}
    got = {_key(e): e for e in report.entries}
    problems = []
    if report.week != truth.week:
        problems.append(f"week is {report.week}, expected {truth.week}")
    for e in report.entries:
        if len(e.practice) != 3:
            problems.append(f"{e.player}: {len(e.practice)} practice days, expected 3 (Wed, Thu, Fri)")
    correct = total = 0
    for key, t in want.items():
        g = got.get(key)
        if g is None:
            problems.append(f"missing row: {t.player} ({t.team})")
            continue
        for field in FIELDS:
            total += 1
            expected, actual = getattr(t, field), getattr(g, field)
            same = expected == actual if field != "injury" else expected.lower() == actual.strip().lower()
            correct += same
            if not same:
                problems.append(f"{t.player}: {field} is {actual!r}, expected {expected!r}")
    for key in got.keys() - want.keys():
        problems.append(f"extra row not in the report: {got[key].player} ({got[key].team})")
    return {"field_accuracy": correct / total if total else 0.0, "rows_found": len(want.keys() & got.keys()),
            "rows_expected": len(want), "problems": problems}  # fmt: skip
